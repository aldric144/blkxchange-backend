def seed_articles():
    """Seed the 3 featured articles into the articles database"""
    conn = sqlite3.connect('articles.db')
    cursor = conn.cursor()
    
    print("🌱 Seeding The Black Chronicle featured articles...")
    print(f"📅 Timestamp: {datetime.now().isoformat()}\n")
    
    seeded_count = 0
    
    for article in ARTICLES:
        cursor.execute("SELECT id FROM articles WHERE title = ?", (article["title"],))
        existing = cursor.fetchone()
        
        if existing:
            print(f"⚠️  Article already exists: {article['title'][:60]}...")
            continue
        
        cursor.execute("""
            INSERT INTO articles (title, category, body, author, image_url, created_at)
            VALUES (?, ?, ?, ?, ?, ?)
        """, (
            article["title"],
            article["category"],
            article["body"],
            article["author"],
            article["image_url"],
            datetime.now().isoformat()
        ))
        
        article_id = cursor.lastrowid
        seeded_count += 1
        
        print(f"✅ Seeded Article #{article_id}")
        print(f"   Title: {article['title']}")
        print(f"   Category: {article['category']}")
        print(f"   Author: {article['author']}")
        print(f"   Image: {article['image_url'][:60]}...")
        print()
    
    conn.commit()
    
    cursor.execute("SELECT COUNT(*) FROM articles")
    total_count = cursor.fetchone()[0]
    
    print(f"\n📊 Summary:")
    print(f"   Articles seeded: {seeded_count}")
    print(f"   Total articles in database: {total_count}")
    
    print(f"\n📰 Latest articles (sorted by created_at DESC):")
    cursor.execute("""
        SELECT id, title, author, category, created_at 
        FROM articles 
        ORDER BY created_at DESC 
        LIMIT 3
    """)
    
    for row in cursor.fetchall():
        print(f"   ID {row[0]}: {row[1][:50]}...")
        print(f"           By {row[2]} | {row[3]} | {row[4]}")
    
    conn.close()
    print("\n✅ Seeding complete!")

if __name__ == "__main__":
    seed_articles()
